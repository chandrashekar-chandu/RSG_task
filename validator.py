"""
SQL Security Validator & Guardrail Module
==========================================
Protects the database by validating and sanitizing text-to-SQL queries
prior to execution. Enforces strict read-only execution, prevents SQL injection,
blocks destructive operations, and validates schema references.
"""

import re
from typing import Tuple, List, Set

# Allowed table(s) in the database
ALLOWED_TABLES: Set[str] = {"sales_transactions"}

# Allowed columns in sales_transactions
ALLOWED_COLUMNS: Set[str] = {
    "transaction_id",
    "order_date",
    "product",
    "category",
    "region",
    "sales_channel",
    "quantity",
    "unit_price",
    "discount_amount",
    "gross_revenue",
    "net_revenue",
    "status",
    "*"
}

# Forbidden keywords indicating destructive or state-changing operations
FORBIDDEN_KEYWORDS: List[str] = [
    r"\bDROP\b",
    r"\bDELETE\b",
    r"\bUPDATE\b",
    r"\bINSERT\b",
    r"\bALTER\b",
    r"\bTRUNCATE\b",
    r"\bCREATE\b",
    r"\bREPLACE\b",
    r"\bEXEC\b",
    r"\bEXECUTE\b",
    r"\bPRAGMA\b",
    r"\bATTACH\b",
    r"\bDETACH\b",
    r"\bVACUUM\b",
    r"\bGRANT\b",
    r"\bREVOKE\b",
    r"\bUPSERT\b",
    r"\bINTO\b\s+OUTFILE\b",
    r"\bLOAD_FILE\b",
    r"\bSLEEP\b"
]


def sanitize_sql_string(raw_sql: str) -> str:
    """
    Cleans raw SQL generated by LLM or user:
    - Removes markdown code fences (```sql ... ```).
    - Trims extraneous whitespace.
    - Removes trailing semicolons for single-statement execution.
    """
    sql = raw_sql.strip()

    # Strip markdown code blocks
    if sql.startswith("```"):
        sql = re.sub(r"^```[a-zA-Z]*\n?", "", sql)
        sql = re.sub(r"\n?```$", "", sql)
        sql = sql.strip()

    # Remove inline single-line SQL comments (-- comment)
    sql = re.sub(r"--.*$", "", sql, flags=re.MULTILINE)
    # Remove multiline comments (/* comment */)
    sql = re.sub(r"/\*.*?\*/", "", sql, flags=re.DOTALL)

    return sql.strip()


def validate_sql(raw_sql: str) -> Tuple[bool, str, str]:
    """
    Validates that a SQL query is completely safe to execute.

    Returns:
        (is_valid: bool, error_message: str, sanitized_sql: str)
    """
    if not raw_sql or not raw_sql.strip():
        return False, "Query cannot be empty.", ""

    clean_sql = sanitize_sql_string(raw_sql)

    # 1. Check for multiple statements (prevent stacked SQL injections)
    # Remove string literals temporarily to avoid false positives on ';' inside strings
    sql_no_strings = re.sub(r"'[^']*'", "''", clean_sql)
    sql_no_strings = re.sub(r'"[^"]*"', '""', sql_no_strings)

    statements = [s.strip() for s in sql_no_strings.split(";") if s.strip()]
    if len(statements) > 1:
        return False, "Multi-statement queries (chained with ';') are prohibited for security.", ""

    # Trailing semicolon removal
    clean_sql = clean_sql.rstrip(";").strip()

    # 2. Enforce query must start strictly with SELECT or WITH (for CTEs)
    first_token_match = re.match(r"^\s*([a-zA-Z]+)", clean_sql)
    if not first_token_match:
        return False, "Invalid SQL syntax: Query must start with a valid command.", ""

    first_keyword = first_token_match.group(1).upper()
    if first_keyword not in ("SELECT", "WITH"):
        return False, f"Security Violation: Only read-only queries (SELECT / WITH) are permitted. Received: {first_keyword}", ""

    # 3. Check against forbidden destructive operations
    upper_sql = clean_sql.upper()
    for pattern in FORBIDDEN_KEYWORDS:
        if re.search(pattern, upper_sql, re.IGNORECASE):
            match = re.search(pattern, upper_sql, re.IGNORECASE).group(0)
            return False, f"Security Violation: Query contains prohibited state-changing keyword '{match}'.", ""

    # 4. Table whitelist validation
    # Check that referenced table exists in ALLOWED_TABLES
    # Looks for FROM <table> or JOIN <table>
    table_matches = re.findall(r"\b(?:FROM|JOIN)\s+([a-zA-Z0-9_]+)", clean_sql, re.IGNORECASE)
    for tbl in table_matches:
        tbl_clean = tbl.lower().strip()
        # CTEs may be referenced as well; if it's not the primary table, verify it
        if tbl_clean not in ALLOWED_TABLES and not re.search(rf"\bWITH\s+{tbl_clean}\b", clean_sql, re.IGNORECASE):
            return False, f"Access Denied: Table '{tbl}' is not authorized for querying. Allowed tables: {', '.join(ALLOWED_TABLES)}.", ""

    return True, "", clean_sql


if __name__ == "__main__":
    test_queries = [
        ("SELECT * FROM sales_transactions LIMIT 5;", True),
        ("DROP TABLE sales_transactions;", False),
        ("SELECT * FROM sales_transactions; DELETE FROM sales_transactions;", False),
        ("UPDATE sales_transactions SET net_revenue = 0;", False),
        ("SELECT product, SUM(net_revenue) FROM sales_transactions GROUP BY product;", True),
        ("SELECT * FROM sqlite_master;", False)
    ]

    print("Running Validator Unit Checks...")
    for q, expected in test_queries:
        valid, err, _ = validate_sql(q)
        status = "PASSED" if valid == expected else "FAILED"
        print(f"[{status}] Valid={valid} (Expected {expected}) | Query: {q[:40]}... {f'Error: {err}' if not valid else ''}")
